// Builds src/theme/tokens.ts from design/tokens.json (the 919 Design System export).
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'));
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const themes = src.color.themes.map((t) => t.id);
const colors = {};
for (const theme of themes) {
  const raw = Object.fromEntries(
    src.color.tokens.map((t) => [t.name, typeof t.value === 'string' ? t.value : t.value[theme] ?? t.value[themes[0]]]),
  );
  const resolve = (v, depth = 0) =>
    typeof v === 'string' && v.startsWith('{') && depth < 5 ? resolve(raw[v.slice(1, -1)], depth + 1) : v;
  colors[theme] = Object.fromEntries(Object.keys(raw).map((k) => [camel(k), resolve(raw[k])]));
}

const px = (v) => (typeof v === 'string' && v.endsWith('px') ? Number(v.slice(0, -2)) : v);
const spacing = Object.fromEntries(src.spacing.tokens.map((t) => [camel(t.name), px(t.value)]));
const radius = Object.fromEntries(src.radius.tokens.map((t) => [camel(t.name), px(t.value)]));

// "0 2px 8px rgba(14,26,43,0.08)" -> RN shadow props (iOS + web boxShadow; Android uses elevation).
const shadows = Object.fromEntries(
  (src.shadow?.tokens ?? []).map((t) => {
    const m = t.value.match(/^(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(\d+)(?:px)?\s+(rgba?\([^)]*\))$/);
    const [, x, y, blur, color] = m;
    const alpha = Number((color.match(/,\s*([\d.]+)\)$/) || [])[1] ?? 1);
    return [camel(t.name), { boxShadow: t.value, elevation: Math.max(1, Math.round(Number(blur) / 3)), _x: +x, _y: +y, _alpha: alpha }];
  }),
);

const type = {};
for (const g of src.type.groups) for (const s of g.styles) {
  type[camel(s.name)] = { family: g.family, fontSize: px(s.fontSize), lineHeight: px(s.lineHeight), fontWeight: s.fontWeight };
}

const out = `// GENERATED by scripts/build-tokens.mjs from design/tokens.json — do not edit by hand.
// Source of truth: 919 Design System. Re-export tokens.json there and run \`npm run tokens\`.

export const palette = ${JSON.stringify(colors, null, 2)} as const;

export type ColorScheme = keyof typeof palette;
export type Colors = { [K in keyof (typeof palette)['light']]: string };

export const spacing = ${JSON.stringify(spacing, null, 2)} as const;

export const radius = ${JSON.stringify(radius, null, 2)} as const;

export const shadowTokens = ${JSON.stringify(Object.fromEntries(Object.entries(shadows).map(([k, v]) => [k, { boxShadow: v.boxShadow, elevation: v.elevation }])), null, 2)} as const;

export const typeScale = ${JSON.stringify(type, null, 2)} as const;
`;
writeFileSync(new URL('../src/theme/tokens.ts', import.meta.url), out);
console.log(`tokens: ${Object.keys(colors.light).length} colors × ${themes.length} themes, ${Object.keys(shadows).length} shadows`);
